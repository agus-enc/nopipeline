#!/bin/sh
# Manual check of the Debian recipe (not part of npm test). Builds the OBS source from the current HEAD tree in a throwaway
# signed repo, with a throwaway OpenPGP repo key standing in for the OBS one, lays the sources out the way OBS's
# debtransform does, builds the .deb in ubuntu:26.04 and installs it there, then installs the same .deb in debian:13.
# Needs git, ssh-keygen, gpg, curl, npm, Docker, and the network (npm, container images, apt, and NodeSource for debian:13).
# It builds from `git archive HEAD`: commit your changes before running it. Touches only temp folders.
# The containers install with Recommends off, so libnotify-bin and xdg-utils are not pulled in.
# Run from the repository root: packaging/debian/check-deb.sh
# With --from <folder> it skips the throwaway keys and repo and checks the files in <folder> instead (the release
# workflow's output folder), so CI tests exactly the files it publishes.
#
# debtransform (https://github.com/openSUSE/obs-build/blob/master/debtransform) maps each debian.<name> next to the dsc to
# debian/<name> on top of the unpacked Debtransform-Tar tarball; the dsc's Files/Checksums lines are regenerated by OBS.
set -eu

[ -f packaging/build-source.sh ] || { echo "check-deb: run this from the repository root" >&2; exit 1; }

from=
if [ "${1:-}" = "--from" ]; then
  [ $# -eq 2 ] && [ -d "$2" ] || { echo "usage: packaging/debian/check-deb.sh [--from <folder with the release files>]" >&2; exit 1; }
  from=$(cd "$2" && pwd)
elif [ $# -ne 0 ]; then
  echo "usage: packaging/debian/check-deb.sh [--from <folder with the release files>]" >&2
  exit 1
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
# Same rule as build-source.sh: git must not depend on the caller's configuration.
for name in $(env | sed -n 's/^\(GIT_[A-Za-z0-9_]*\)=.*/\1/p'); do unset "$name"; done
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null GIT_CONFIG_NOSYSTEM=1

step() { printf '\n== %s\n' "$*"; }
version=$(node -p "require('./package.json').version")

make_source() {
  step "throwaway repo key (OpenPGP, in a temporary GNUPGHOME) served to obs-key.sh through file://"
  mkdir -m 700 "$work/gnupg"
  GNUPGHOME="$work/gnupg" gpg --batch --quiet --passphrase '' --quick-generate-key 'check-deb <check-deb@example.invalid>' ed25519 sign never
  fpr=$(GNUPGHOME="$work/gnupg" gpg --batch --with-colons --list-keys | awk -F: '$1=="fpr"{print $10; exit}')
  GNUPGHOME="$work/gnupg" gpg --batch --quiet --export "$fpr" >"$work/repo-key.gpg"
  sh packaging/obs-key.sh "file://$work/repo-key.gpg" "$fpr" "$work/obs"
  ls -l "$work/obs/keys"

  step "throwaway signing key and signed repo for v$version (from the current HEAD tree)"
  ssh-keygen -q -N '' -t ed25519 -f "$work/key"
  mkdir "$work/repo"
  git archive HEAD | tar -x -C "$work/repo"
  git -C "$work/repo" init --quiet --initial-branch=main
  git -C "$work/repo" add -A
  git -C "$work/repo" -c user.name=Check -c user.email=check@example.com commit --quiet -m "check"
  git -C "$work/repo" -c user.name=Check -c user.email=check@example.com -c gpg.format=ssh -c "user.signingkey=$work/key" \
    tag -s -m "v$version" "v$version"

  step "build-source.sh with the throwaway key and the throwaway repo key"
  signer="releases $(cut -d' ' -f1,2 "$work/key.pub")"
  sed "s|@RELEASE_SIGNERS@|$signer|" packaging/build-source.sh >"$work/build-source.sh"
  mkdir "$src"
  NOPIPELINE_REPO_KEYS="$work/obs/keys" sh "$work/build-source.sh" "$work/repo" "$src"
  ls -l "$src"
}

if [ -n "$from" ]; then
  src=$from
  step "using the release files in $src"
else
  src="$work/src"
  make_source
fi
for f in nopipeline.dsc debian.control debian.copyright debian.rules debian.changelog; do
  [ -f "$src/$f" ] || { echo "check-deb: build-source.sh did not write $f" >&2; exit 1; }
done
cat "$src/nopipeline.dsc"

# Runs inside ubuntu:26.04: lay out debian/ like debtransform, build, check the package contents.
cat >"$work/build.sh" <<'INNER'
set -eu
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq --no-install-recommends build-essential debhelper dpkg-dev fakeroot >/dev/null
mkdir /build
tar -xzf /src/nopipeline.tar.gz -C /build
cd /build/nopipeline-*/
mkdir debian
for f in /src/debian.*; do cp "$f" "debian/${f##*/debian.}"; done
chmod +x debian/rules   # dpkg-source does this when OBS unpacks the source
dpkg-buildpackage -us -uc -b
mkdir -p /out
cp /build/nopipeline_*_all.deb /out/
deb=$(ls /out/nopipeline_*_all.deb)
# A changelog from another release must stop the build (debian.rules compares it with version.json). The check runs
# before anything is installed, so nothing needs cleaning up afterwards.
cp debian/changelog /tmp/changelog.keep
sed -i '1s/^nopipeline ([^)]*)/nopipeline (0.0.1-1)/' debian/changelog
if debian/rules override_dh_auto_install >/tmp/mixed.log 2>&1; then echo "check-deb: a mixed version was not refused" >&2; exit 1; fi
grep -q 'sources are from two releases' /tmp/mixed.log || { echo "check-deb: unexpected failure for a mixed version" >&2; cat /tmp/mixed.log >&2; exit 1; }
cp /tmp/changelog.keep debian/changelog
dpkg-deb -I "$deb"
dpkg-deb -c "$deb"
dpkg-deb -f "$deb" Depends | grep -qx 'nodejs (>= 22.22)' || { echo "check-deb: unexpected Depends" >&2; exit 1; }
dpkg-deb -f "$deb" Architecture | grep -qx all
listing=$(dpkg-deb -c "$deb")
printf '%s\n' "$listing" | grep -q ' \./usr/share/keyrings/nopipeline-archive-keyring.gpg$'
printf '%s\n' "$listing" | grep -q ' \./usr/bin/nopipeline$'
# The images' dpkg config skips /usr/share/doc on install, so the documents are checked in the package itself.
for f in copyright LICENSE LICENSE.notionhq-client LICENSE.node-diff3 README.md CHANGELOG.md; do
  printf '%s\n' "$listing" | grep -Eq " \./usr/share/doc/nopipeline/$f(\.gz)?\$" || { echo "check-deb: $f is missing" >&2; exit 1; }
done
INNER

# Runs in ubuntu:26.04 and debian:13. Node 22.x comes from NodeSource, configured as its setup script does (its deb822 file;
# https://deb.nodesource.com/setup_22.x, read, not run): the distributions' own nodejs packages are built without
# TypeScript support, so nopipeline cannot run on them (the line below prints the archive candidate).
# Then the .deb is installed and run.
cat >"$work/install.sh" <<'INNER'
set -eu
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq --no-install-recommends ca-certificates curl gpg >/dev/null
echo "archive nodejs: $(apt-cache policy nodejs | sed -n 's/^  Candidate: //p')"
curl -fsSL https://deb.nodesource.com/gpgkey/nodesource-repo.gpg.key | gpg --dearmor -o /usr/share/keyrings/nodesource.gpg
chmod 644 /usr/share/keyrings/nodesource.gpg
cat >/etc/apt/sources.list.d/nodesource.sources <<EOF
Types: deb
URIs: https://deb.nodesource.com/node_22.x
Suites: nodistro
Components: main
Architectures: $(dpkg --print-architecture)
Signed-By: /usr/share/keyrings/nodesource.gpg
EOF
apt-get update -qq
apt-get install -y -qq --no-install-recommends /debs/nopipeline_*_all.deb >/dev/null
node --version
nopipeline --version
nopipeline --help >/dev/null
test -f /usr/share/keyrings/nopipeline-archive-keyring.gpg
[ "$(stat -c %a /usr/share/keyrings/nopipeline-archive-keyring.gpg)" = 644 ]
[ "$(stat -c %a /usr/bin/nopipeline)" = 755 ]
cmp /usr/bin/nopipeline /launcher.sh
INNER

# Runs in ubuntu:26.04 with the archive's own nodejs (built without TypeScript support): the package installs, and the
# launcher explains instead of failing with ERR_UNKNOWN_FILE_EXTENSION.
cat >"$work/archive-node.sh" <<'INNER'
set -eu
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq --no-install-recommends nodejs /debs/nopipeline_*_all.deb >/dev/null
echo "archive node: $(node --version)"
cmp /usr/bin/nopipeline /launcher.sh
want="nopipeline: this Node.js ($(node --version)) cannot run TypeScript. Install Node.js 22.22 or newer from NodeSource (https://github.com/nodesource/distributions), which can."
status=0
nopipeline --version >/tmp/out 2>/tmp/err || status=$?
cat /tmp/err
if [ "$status" = 0 ]; then
  # Ubuntu's Node can run TypeScript now: the package works with the archive's own Node, which is better than the message.
  echo "check-deb: NOTE: the archive Node in this image supports TypeScript; the 'cannot run TypeScript' message is not testable here"
  [ -s /tmp/out ] || { echo "check-deb: nopipeline --version printed nothing" >&2; exit 1; }
else
  [ "$status" = 1 ] || { echo "check-deb: expected exit 1 with the archive Node, got $status" >&2; exit 1; }
  [ ! -s /tmp/out ] || { echo "check-deb: unexpected stdout" >&2; exit 1; }
  [ "$(cat /tmp/err)" = "$want" ] || { echo "check-deb: unexpected message" >&2; exit 1; }
fi
INNER

mkdir "$work/debs"
step "ubuntu:26.04: debtransform-style layout, dpkg-buildpackage"
docker run --rm -v "$src:/src:ro,z" -v "$work/build.sh:/build.sh:ro,z" -v "$work/debs:/out:z" ubuntu:26.04 sh /build.sh
ls -l "$work/debs"

for image in ubuntu:26.04 debian:13; do
  step "$image with NodeSource 22.x: install the .deb and run it"
  docker run --rm -v "$work/debs:/debs:ro,z" -v "$work/install.sh:/install.sh:ro,z" -v "$PWD/packaging/nopipeline-launcher.sh:/launcher.sh:ro,z" "$image" sh /install.sh
done

step "ubuntu:26.04 with the archive's nodejs: the launcher says it cannot run TypeScript"
docker run --rm -v "$work/debs:/debs:ro,z" -v "$work/archive-node.sh:/archive-node.sh:ro,z" -v "$PWD/packaging/nopipeline-launcher.sh:/launcher.sh:ro,z" ubuntu:26.04 sh /archive-node.sh

step "all checks passed"
